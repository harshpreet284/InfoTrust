def _get_positive_float_env(var_name: str, default: float) -> float:
    raw = os.environ.get(var_name)
    if raw is None:
        return default
    try:
        val = float(raw)
        if math.isfinite(val) and val > 0:
            return val
    except (ValueError, TypeError):
        pass
    return default


